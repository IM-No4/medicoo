const { withProjectBuildGradle } = require('expo/config-plugins');

// Notifee ships its native core as an AAR inside the npm package, laid out as a local Maven repository
// (node_modules/@notifee/react-native/android/libs). Gradle only finds `app.notifee:core` if that folder is listed as a repository;
// the library adds it to its own project, but a root build that resolves repositories centrally ("Could not find any matches for
// app.notifee:core:+") never sees that. Listing it on the root project fixes the build.
//
// A config plugin (not a hand edit of android/build.gradle) because android/ is regenerated by `expo prebuild`.
const MAVEN_LINE = `    maven { url "$rootDir/../node_modules/@notifee/react-native/android/libs" }`;

module.exports = function withNotifeeLocalMaven(config) {
    return withProjectBuildGradle(config, (config) => {
        if (config.modResults.language !== 'groovy') {
            throw new Error('withNotifeeLocalMaven only supports Groovy project build.gradle');
        }
        if (!config.modResults.contents.includes('@notifee/react-native/android/libs')) {
            // Into allprojects { repositories { ... } }
            config.modResults.contents = config.modResults.contents.replace(
                /(allprojects\s*{[\s\S]*?repositories\s*{)/,
                (match) => `${match}\n${MAVEN_LINE}`
            );
        }
        return config;
    });
};
